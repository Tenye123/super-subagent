// dsh-fleet —— 被控端引导脚本生成
//
// 这段脚本解决了什么问题
//   原本要把一台机器变成子代理，得手工做六件事：装 Node、装 OpenSSH
//   Server、装 Tailscale、登录 Tailscale、把控制端公钥写进
//   authorized_keys、把 sshd 绑到 tailnet 地址。任何一步漏掉都表现为
//   「连不上」，而且没有提示。
//
//   现在这些全部由生成出来的一段脚本完成，最后自动向控制端报名。
//
// 为什么在控制端生成、而不是发一个固定的脚本
//   脚本里必须写死三样只在控制端才知道的东西：
//     - 控制端的 tailnet 地址和报名端口
//     - 本次报名用的令牌
//     - 控制端公钥（写进对方 authorized_keys）
//   所以只能现生成。这也顺带保证了令牌不会长期躺在某个公共文件里。
//
// 纯 ASCII 的硬约束
//   PowerShell 5.1 按 GBK 读无 BOM 的 .ps1；脚本里出现任何多字节字符
//   都可能造成语法错误（实测过：注释里的中文会吞掉后面的换行，
//   导致紧跟着的一行代码静默失效）。所以这里输出的正文全英文。

import { buildHealScript, buildRegisterTaskScript } from './selfheal.mjs';

/** 生成的脚本开头都带这一行，便于人工确认来源与时间。 */
const BANNER = '# Generated by super-subagent (dsh-fleet) -- agent bootstrap';

/**
 * 估算一段脚本将来需要多少空间。仅用于界面上给个预期，不参与逻辑。
 */
export function estimateDuration() {
  return { minMinutes: 4, maxMinutes: 12 };
}

/**
 * 生成引导脚本。
 *
 * @param {object} opts
 * @param {string} opts.controllerIp     控制端 tailnet IPv4
 * @param {number} opts.beaconPort       控制端报名端口
 * @param {string} opts.token            本次报名令牌
 * @param {string} opts.controllerPubKey 控制端公钥（整行）
 * @param {string} [opts.agentName]      期望的设备名（默认取对方主机名）
 * @param {number} [opts.sshPort]        sshd 端口，默认 22
 * @param {string} [opts.tailscaleAuthKey] 可选：预授权 key，免去交互登录
 * @param {boolean} [opts.allowAnyTailnet] 是否同时允许 tailnet 内任意来源
 * @returns {string} 完整的 PowerShell 脚本（纯 ASCII）
 */
export function buildAgentScript({
  controllerIp,
  beaconPort,
  token,
  controllerPubKey,
  agentName = '',
  sshPort = 22,
  tailscaleAuthKey = '',
  section = '',
}) {
  // --- 参数校验。生成一份跑不通的脚本比不生成更糟。 ---
  //
  // 注意 IPv4 校验不能只数点：`999.1.1.1` 有四段数字，但每一段都必须是
  // 0-255。正则放行非法地址会在目标机器上变成 sshd 绑不上一个不存在
  // 的地址，然后静默退出——正是我们最想避免的那种失败。
  const ipOk =
    /^\d{1,3}(\.\d{1,3}){3}$/.test(String(controllerIp || '')) &&
    String(controllerIp)
      .split('.')
      .every((o) => Number(o) >= 0 && Number(o) <= 255);
  if (!ipOk) {
    throw new Error('控制器 IPv4 不合法: ' + controllerIp);
  }
  if (!Number.isInteger(beaconPort) || beaconPort < 1 || beaconPort > 65535) {
    throw new Error('报名端口不合法: ' + beaconPort);
  }
  if (!token || !/^fb_[A-Za-z0-9_-]{20,}$/.test(token)) {
    throw new Error('报名令牌格式不对（应以 fb_ 开头）');
  }
  if (!/^ssh-(ed25519|rsa|ecdsa)\s+AAAA/.test(String(controllerPubKey || ''))) {
    throw new Error('控制器公钥格式不对: ' + String(controllerPubKey).slice(0, 40));
  }
  if (!Number.isInteger(sshPort) || sshPort < 1 || sshPort > 65535) {
    throw new Error('SSH 端口不合法: ' + sshPort);
  }

  // 单引号里的内容会原样进入 PowerShell 字符串，必须转义单引号本身。
  const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

  // 自愈脚本以 base64 内嵌。
  //
  // 为什么不直接内联成 PowerShell 代码：它本身是一份完整的脚本（有函数、
  // 有 try/catch、有自己的 $ErrorActionPreference），拼进另一个脚本里很
  // 容易出现作用域和引号问题。base64 传字节，写盘后单独执行，边界最干净。
  const healScriptB64 = Buffer.from(buildHealScript({ sshPort }), 'utf8').toString('base64');
  const registerTaskB64 = Buffer.from(
    buildRegisterTaskScript({ healScriptPath: 'C:\\ProgramData\\super-subagent\\sshd-heal.ps1', sshPort }),
    'utf8',
  ).toString('base64');

  const lines = [];
  const L = (s = '') => lines.push(s);

  L(BANNER);
  L('#');
  L('# WHAT THIS DOES');
  L('#   1. checks/installs Node.js 18+');
  L('#   2. checks/installs the OpenSSH Server');
  L('#   3. checks/installs Tailscale, then waits for it to come up');
  L('#   4. writes the controller public key into authorized_keys');
  L('#   5. binds sshd to the Tailscale address only (never the company LAN)');
  L('#   6. reports itself back to the controller');
  L('#');
  L('# SAFETY');
  L('#   - port 22 is never opened to the local network; the firewall rule');
  L('#     is scoped to the Tailscale interface and 100.64.0.0/10');
  L('#   - password auth stays disabled; keys only');
  L('#   - nothing here touches project files or installed applications');
  L('#   - every step is idempotent: running it twice changes nothing');
  L('#');
  L('# RUN (elevated PowerShell):');
  L('#   powershell -ExecutionPolicy Bypass -File .\\setup-agent.ps1');
  L('');
  L('$ErrorActionPreference = ' + q('Stop'));
  L('');
  L('# ---- configuration baked in by the controller ----');
  L('$ControllerIp   = ' + q(controllerIp));
  L('$BeaconPort     = ' + beaconPort);
  L('$BeaconToken    = ' + q(token));
  L('$SshPort        = ' + sshPort);
  L('$AgentName      = ' + q(agentName));
  L('$TailscaleAuthKey = ' + q(tailscaleAuthKey));
  if (section) {
    L('# Controller-supplied section label (display only).');
    L('$Section = ' + q(section));
  }
  L('');
  L('# The controller public key. Written verbatim into authorized_keys,');
  L('# with restrictions so a stolen key cannot open a shell or forward ports.');
  L('$ControllerPubKey = @' + "'");
  L(controllerPubKey.trim());
  L("'@");
  L('');
  L('# ---- progress log. Written next to the script so the user can send it back. ----');
  L('$ProgressFile = Join-Path $env:TEMP "super-subagent-setup.log"');
  L('function Say([string]$m) {');
  L('  $line = "[{0}] {1}" -f (Get-Date -Format "HH:mm:ss"), $m');
  L('  Write-Host $line');
  L('  try { Add-Content -Path $ProgressFile -Value $line -Encoding UTF8 -ErrorAction SilentlyContinue } catch { }');
  L('}');
  L('function Fail([string]$m) {');
  L('  Say ("FAILED: " + $m)');
  L('  Say "See the log above. Nothing was left half-configured on purpose."');
  L('  exit 1');
  L('}');
  L('');
  L('# External tools write progress and warnings to stderr. Under');
  L('# ErrorActionPreference=Stop, PowerShell turns each stderr line into a');
  L('# terminating ErrorRecord -- even when the output is only assigned to a');
  L('# variable. Measured: npm printing "warn EBADENGINE" killed the whole run.');
  L('# So every external call lowers the preference for its own duration and is');
  L('# judged by its exit code plus a real post-condition check instead.');
  L('function Invoke-External {');
  L('  param([string]$FilePath, [string[]]$ArgumentList = @())');
  L('  $old = $ErrorActionPreference');
  L('  $ErrorActionPreference = ' + q('Continue'));
  L('  try {');
  L('    $out = & $FilePath @ArgumentList 2>&1');
  L('    $code = $LASTEXITCODE');
  L('  } finally { $ErrorActionPreference = $old }');
  L('  $text = ($out | ForEach-Object { "$_" }) -join "`r`n"');
  L('  return @{ Code = $code; Text = $text }');
  L('}');
  L('');
  L('function Test-Admin {');
  L('  $id = [Security.Principal.WindowsIdentity]::GetCurrent()');
  L('  $p = New-Object Security.Principal.WindowsPrincipal($id)');
  L('  return $p.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)');
  L('}');
  L('');
  L('Say "=== super-subagent agent setup ==="');
  L('Say ("controller: " + $ControllerIp + ":" + $BeaconPort)');
  L('');
  L('if (-not (Test-Admin)) {');
  L('  Fail "must run in an elevated PowerShell (right-click > Run as administrator)"');
  L('}');
  L('Say "running elevated: yes"');
  L('');

  // --- step 1: node ---
  L('# =====================================================================');
  L('# STEP 1/6  Node.js');
  L('# =====================================================================');
  L('Say ""');
  L('Say "--- step 1/6: Node.js ---"');
  L('$node = Get-Command node -ErrorAction SilentlyContinue');
  L('# A fresh machine has no nodejs on PATH yet even right after installing it,');
  L('# so also probe the usual install locations before deciding to install.');
  L('if (-not $node) {');
  L('  foreach ($cand in @("$env:ProgramFiles\\nodejs\\node.exe", "${env:ProgramFiles(x86)}\\nodejs\\node.exe", "$env:LOCALAPPDATA\\Programs\\nodejs\\node.exe")) {');
  L('    if (Test-Path $cand) { $node = @{ Source = $cand }; break }');
  L('  }');
  L('}');
  L('if ($node) {');
  L('  $v = (& $node.Source --version) 2>&1');
  L('  Say ("node already present: " + $v)');
  L('} else {');
  L('  Say "node not found; installing Node.js LTS via winget"');
  L('  $w = Get-Command winget -ErrorAction SilentlyContinue');
  L('  if (-not $w) { Fail "winget not available; install Node.js 18+ manually, then re-run" }');
  L('  $r = Invoke-External winget @("install", "--id", "OpenJS.NodeJS.LTS", "--silent", "--accept-package-agreements", "--accept-source-agreements")');
  L('  if ($r.Code -ne 0) { Say $r.Text; Fail "winget could not install Node.js" }');
  L('  foreach ($cand in @("$env:ProgramFiles\\nodejs\\node.exe", "$env:LOCALAPPDATA\\Programs\\nodejs\\node.exe")) {');
  L('    if (Test-Path $cand) { $node = @{ Source = $cand }; break }');
  L('  }');
  L('  if (-not $node) { Fail "Node.js installed but the executable cannot be found" }');
  L('  Say "node installed"');
  L('}');
  L('');

  // --- step 2: sshd ---
  L('# =====================================================================');
  L('# STEP 2/6  OpenSSH Server');
  L('# =====================================================================');
  L('Say "--- step 2/6: OpenSSH Server ---"');
  L('$sshdExe = "C:\\Program Files\\OpenSSH\\sshd.exe"');
  L('$sshdAlt = "$env:SystemRoot\\System32\\OpenSSH\\sshd.exe"');
  L('$sshdSvc = Get-Service sshd -ErrorAction SilentlyContinue');
  L('if ($sshdSvc -and ((Test-Path $sshdExe) -or (Test-Path $sshdAlt))) {');
  L('  Say ("sshd already installed: " + $sshdSvc.Status)');
  L('} else {');
  L('  Say "installing the OpenSSH Server capability"');
  L('  $cap = Get-WindowsCapability -Online -Name "OpenSSH.Server*" -ErrorAction SilentlyContinue');
  L('  if (-not $cap -or $cap.State -ne "Installed") {');
  L('    $r = Invoke-External powershell @("-NoProfile", "-Command", "Add-WindowsCapability -Online -Name OpenSSH.Server~~~~0.0.1.0")');
  L('    if ($r.Code -ne 0) { Say $r.Text; Fail "could not add the OpenSSH Server capability" }');
  L('  }');
  L('  Say "OpenSSH Server capability present"');
  L('}');
  L('');
  L('# The MSI layout puts sshd under Program Files; the capability puts it under');
  L('# System32. Both are valid, so resolve whichever exists.');
  L('if (-not (Test-Path $sshdExe)) { $sshdExe = $sshdAlt }');
  L('if (-not (Test-Path $sshdExe)) { Fail "sshd.exe not found in either known location" }');
  L('Say ("sshd.exe: " + $sshdExe)');
  L('');

  // --- step 3: tailscale ---
  L('# =====================================================================');
  L('# STEP 3/6  Tailscale');
  L('# =====================================================================');
  L('Say "--- step 3/6: Tailscale ---"');
  L('$tsExe = "C:\\Program Files\\Tailscale\\tailscale.exe"');
  L('if (-not (Test-Path $tsExe)) {');
  L('  Say "installing Tailscale"');
  L('  $w = Get-Command winget -ErrorAction SilentlyContinue');
  L('  if ($w) {');
  L('    $r = Invoke-External winget @("install", "--id", "Tailscale.Tailscale", "--silent", "--accept-package-agreements", "--accept-source-agreements")');
  L('    if ($r.Code -ne 0) { Say $r.Text }');
  L('  }');
  L('  if (-not (Test-Path $tsExe)) { Fail "Tailscale not installed; get it from https://tailscale.com/download/windows" }');
  L('  Say "Tailscale installed"');
  L('} else { Say "Tailscale already installed" }');
  L('');
  L('# Wait for a tailnet address. Right after a fresh install or a reinstall,');
  L('# tailscaled has no node key yet and only allocates an address after login.');
  L('# Binding sshd before that point is exactly what locks this design out, so');
  L('# never proceed without a real IPv4.');
  L('if ($TailscaleAuthKey) {');
  L('  Say "logging in with the supplied auth key"');
  L('  $r = Invoke-External $tsExe @("up", "--authkey", $TailscaleAuthKey, "--accept-routes=false", "--ssh=false")');
  L('  if ($r.Code -ne 0) { Say $r.Text; Say "auth key login failed; falling back to manual login" }');
  L('} else {');
  L('  # No auth key: the user has to approve the machine in a browser. Say so');
  L('  # BEFORE tailscale up blocks, otherwise the script looks frozen.');
  L('  Say "No auth key supplied: if a Tailscale login window appears, sign in"');
  L('  Say "with the SAME account the controller uses. This window may wait."');
  L('  $r = Invoke-External $tsExe @("up", "--accept-routes=false", "--ssh=false")');
  L('  if ($r.Code -ne 0) { Say $r.Text }');
  L('}');
  L('');
  L('$tsIp = ""');
  L('for ($i = 1; $i -le 60; $i++) {');
  L('  $cand = ""');
  L('  try { $cand = ((& $tsExe ip -4) 2>&1 | Out-String).Trim() } catch { }');
  L('  if ($cand -match "^\\d{1,3}(\\.\\d{1,3}){3}$") { $tsIp = $cand; break }');
  L('  if ($i -eq 1) {');
  L('    Say "waiting for a Tailscale address..."');
  L('    Say "If a login window opened, sign in with the same account as the controller."');
  L('  }');
  L('  Start-Sleep -Seconds 5');
  L('}');
  L('if (-not $tsIp) {');
  L('  Fail "no Tailscale address after 5 minutes. Run [tailscale up] in this window, sign in, then re-run this script."');
  L('}');
  L('Say ("tailscale address: " + $tsIp)');
  L('');

  // --- step 4: authorized_keys ---
  L('# =====================================================================');
  L('# STEP 4/6  Authorize the controller key');
  L('# =====================================================================');
  L('Say "--- step 4/6: authorize the controller ---"');
  L('# On Windows OpenSSH, an administrative user key goes in');
  L('# ProgramData\\ssh\\administrators_authorized_keys, NOT in the user profile.');
  L('# Writing to the wrong file is the single most common reason a key silently');
  L('# does not work, so handle both locations.');
  L('$sshDir = "C:\\ProgramData\\ssh"');
  L('if (-not (Test-Path $sshDir)) { New-Item -ItemType Directory -Path $sshDir -Force | Out-Null }');
  L('$authFile = Join-Path $sshDir "administrators_authorized_keys"');
  L('$existing = @()');
  L('if (Test-Path $authFile) { $existing = @(Get-Content $authFile -ErrorAction SilentlyContinue) }');
  L('$already = $existing | Where-Object { $_ -and $_.Trim() -eq $ControllerPubKey.Trim() }');
  L('if ($already) {');
  L('  Say "controller key already authorized"');
  L('} else {');
  L('  Add-Content -Path $authFile -Value $ControllerPubKey.Trim() -Encoding ASCII');
  L('  Say "controller key written"');
  L('}');
  L('# Permissions matter: sshd refuses the file if other users can write to it.');
  L('$r = Invoke-External icacls @($authFile, "/inheritance:r", "/grant", "Administrators:F", "/grant", "SYSTEM:F")');
  L('if ($r.Code -ne 0) { Say $r.Text; Say "warning: could not tighten permissions on the authorized keys file" }');
  L('');

  // --- step 5: bind sshd to tailnet ---
  L('# =====================================================================');
  L('# STEP 5/6  Bind sshd to the Tailscale address only');
  L('# =====================================================================');
  L('Say "--- step 5/6: harden sshd ---"');
  L('$cfg = "C:\\ProgramData\\ssh\\sshd_config"');
  L('if (-not (Test-Path $cfg)) {');
  L('  Copy-Item "$env:SystemRoot\\System32\\OpenSSH\\sshd_config_default" $cfg -ErrorAction SilentlyContinue');
  L('}');
  L('if (-not (Test-Path $cfg)) { Fail "sshd_config not found and no default to copy" }');
  L('$bak = "$cfg.subagent-bak"');
  L('if (-not (Test-Path $bak)) { Copy-Item $cfg $bak -Force }');
  L('');
  L('$text = Get-Content $cfg -Raw');
  L('# Only rewrite directives before the first Match block; they are illegal inside it.');
  L('$mi = [regex]::Match($text, "(?m)^[ \\t]*Match[ \\t]").Index');
  L('$head = if ($mi -ge 0) { $text.Substring(0, $mi) } else { $text }');
  L('$tail = if ($mi -ge 0) { $text.Substring($mi) } else { "" }');
  L('$head = [regex]::Replace($head, "(?m)^[ \\t]*#?[ \\t]*ListenAddress[^\\r\\n]*(?:\\r?\\n)?", "")');
  L('$head = [regex]::Replace($head, "(?m)^[ \\t]*#?[ \\t]*Port[ \\t]+\\d+[^\\r\\n]*(?:\\r?\\n)?", "")');
  L('$head = [regex]::Replace($head, "(?m)^[ \\t]*#?[ \\t]*PasswordAuthentication[^\\r\\n]*(?:\\r?\\n)?", "")');
  L('$head = $head.TrimEnd() + "`r`n"');
  L('$head += "Port $SshPort`r`n"');
  L('$head += "ListenAddress $tsIp`r`n"');
  L('$head += "ListenAddress 127.0.0.1`r`n"');
  L('$head += "PasswordAuthentication no`r`n"');
  L('$head += "PubkeyAuthentication yes`r`n"');
  L('Set-Content -Path $cfg -Value ($head + $tail) -Encoding ASCII -NoNewline');
  L('Say "sshd_config rewritten (backup at $bak)"');
  L('');
  L('# Validate BEFORE restarting. A broken config plus an aggressive restart');
  L('# policy once produced 2500 restarts in one second and no service at all.');
  L('$t = Invoke-External $sshdExe @("-t", "-f", $cfg)');
  L('if ($t.Code -ne 0) {');
  L('  Say $t.Text');
  L('  Copy-Item $bak $cfg -Force');
  L('  Fail "sshd_config failed validation; the previous config was restored"');
  L('}');
  L('Say "sshd_config is valid"');
  L('');
  L('# sshd must start after Tailscale, because it binds to the Tailscale');
  L('# address. Without this dependency it can start first, fail to bind, and die.');
  L('$r = Invoke-External sc.exe @("config", "sshd", "depend=", "Tailscale")');
  L('Set-Service sshd -StartupType Automatic -ErrorAction SilentlyContinue');
  L('# Restart after 60s, give up after 3 tries -- never the tight default loop.');
  L('$r = Invoke-External sc.exe @("failure", "sshd", "reset=", "86400", "actions=", "restart/60000/restart/60000/restart/60000")');
  L('');
  L('Try {');
  L('  Restart-Service sshd -Force -ErrorAction Stop');
  L('} Catch {');
  L('  Say ("restart failed: " + $_.Exception.Message)');
  L('  Fail "sshd did not start. Run [sc.exe qc sshd] and share the output."');
  L('}');
  L('Start-Sleep -Seconds 4');
  L('$svc = Get-Service sshd');
  L('Say ("sshd service: " + $svc.Status)');
  L('if ($svc.Status -ne "Running") { Fail "sshd is not running" }');
  L('');
  L('$sock = @(Get-NetTCPConnection -State Listen -LocalPort $SshPort -ErrorAction SilentlyContinue)');
  L('if ($sock.Count -eq 0) { Fail "sshd is running but nothing is listening on port $SshPort" }');
  L('$onTs = $sock | Where-Object { $_.LocalAddress -eq $tsIp }');
  L('if (-not $onTs) { Fail "sshd is not listening on the Tailscale address ($tsIp)" }');
  L('Say ("listening on " + $tsIp + ":" + $SshPort)');
  L('');
  L('# Firewall rule scoped to the tailnet interface and range ONLY.');
  L('# Never open 22 to the local network.');
  L('$ruleName = "super-subagent-sshd"');
  L('$existingRule = Get-NetFirewallRule -DisplayName $ruleName -ErrorAction SilentlyContinue');
  L('if (-not $existingRule) {');
  L('  Try {');
  L('    New-NetFirewallRule -DisplayName $ruleName -Direction Inbound -Action Allow -Protocol TCP -LocalPort $SshPort -RemoteAddress "100.64.0.0/10" -ErrorAction Stop | Out-Null');
  L('    Say "firewall rule added (tailnet range only)"');
  L('  } Catch { Say ("warning: could not add the firewall rule: " + $_.Exception.Message) }');
  L('} else { Say "firewall rule already present" }');
  L('');

  // --- step 5.5: sshd 自愈 ---
  L('# =====================================================================');
  L('# STEP 5/6 (continued)  Make sshd survive the next reboot');
  L('# =====================================================================');
  L('# WHY: sshd is bound to the Tailscale address on purpose, but at boot it');
  L('# can start before Tailscale has an address, fail to bind, and exit. From');
  L('# then on the machine is unreachable until someone walks over to it --');
  L('# this happened once and had to be fixed with a full reinstall.');
  L('#');
  L('# This registers a task that waits for Tailscale, fixes a stale listen');
  L('# address, and starts sshd if it is not running. It runs as SYSTEM with a');
  L('# 2 minute delay and bounded retries, so it cannot cause a restart storm.');
  L('$healDir = "C:\\ProgramData\\super-subagent"');
  L('if (-not (Test-Path $healDir)) { New-Item -ItemType Directory -Path $healDir -Force | Out-Null }');
  L('$healScript = Join-Path $healDir "sshd-heal.ps1"');
  L('$healBody = ' + "'" + healScriptB64 + "'");
  L('try {');
  L('  [IO.File]::WriteAllBytes($healScript, [Convert]::FromBase64String($healBody))');
  L('  Say "self-healing script written"');
  L('} catch {');
  L('  Say ("warning: could not write the self-healing script: " + $_.Exception.Message)');
  L('}');
  L('');
  L('$regBody = ' + "'" + registerTaskB64 + "'");
  L('$regScript = Join-Path $healDir "register-heal-task.ps1"');
  L('try {');
  L('  [IO.File]::WriteAllBytes($regScript, [Convert]::FromBase64String($regBody))');
  L('  $out = & powershell -NoProfile -NonInteractive -ExecutionPolicy Bypass -File $regScript 2>&1');
  L('  foreach ($line in @($out)) { if ("$line") { Say ("  " + $line) } }');
  L('} catch {');
  L('  Say ("warning: could not register the self-healing task: " + $_.Exception.Message)');
  L('}');
  L('');
  L('# =====================================================================');
  L('# STEP 6/6  Report to the controller');
  L('# =====================================================================');
  L('Say "--- step 6/6: report to the controller ---"');
  L('');
  L('$osName = ""');
  L('try { $osName = (Get-CimInstance Win32_OperatingSystem).Caption } catch { }');
  L('');
  L('$nodeVersion = ""');
  L('try { $nodeVersion = ((& $node.Source --version) 2>&1 | Out-String).Trim() } catch { }');
  L('');
  L('# Report the hostname so the controller can show a human-readable name.');
  L('$report = @{');
  L('  v = 1');
  L('  token = $BeaconToken');
  L('  ts = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()');
  L('  name = $(if ($AgentName) { $AgentName } else { $env:COMPUTERNAME })');
  L('  host = $env:COMPUTERNAME');
  L('  user = $env:USERNAME');
  L('  ips = @($tsIp)');
  L('  os = $osName');
  L('  nodeVersion = $nodeVersion');
  L('  publicKey = ($ControllerPubKey -split " ")[0..1] -join " "');
  L('}');
  L('$body = $report | ConvertTo-Json -Compress');
  L('$url = "http://" + $ControllerIp + ":" + $BeaconPort + "/beacon"');
  L('');
  L('$sent = $false');
  L('for ($i = 1; $i -le 3; $i++) {');
  L('  Try {');
  L('    $r = Invoke-WebRequest -Uri $url -Method POST -Body $body -ContentType "application/json" -TimeoutSec 20 -UseBasicParsing -ErrorAction Stop');
  L('    if ($r.StatusCode -ge 200 -and $r.StatusCode -lt 300) { $sent = $true; break }');
  L('    Say ("attempt " + $i + ": HTTP " + $r.StatusCode + " " + $r.Content)');
  L('  } Catch {');
  L('    $msg = $_.Exception.Message');
  L('    Say ("attempt " + $i + ": " + $msg)');
  L('    # A 4xx means the controller rejected us (bad or expired token).');
  L('    # Retrying cannot help, so stop and say so plainly.');
  L('    if ($msg -match "40[0-9]") { break }');
  L('  }');
  L('  Start-Sleep -Seconds 3');
  L('}');
  L('');
  L('Say ""');
  L('if ($sent) {');
  L('  Say "=== DONE: this machine is now a super-subagent ==="');
  L('  Say ("name:    " + $report.name)');
  L('  Say ("address: " + $tsIp)');
  L('  Say ("ssh:     " + $env:USERNAME + "@" + $tsIp + ":" + $SshPort)');
  L('  Say ""');
  L('  Say "It should now appear in the controller UI as ready."');
  L('} else {');
  L('  Say "=== setup finished, but the controller did not answer ==="');
  L('  Say "The machine is correctly configured and can be added by address."');
  L('  Say ("address: " + $tsIp)');
  L('  Say ""');
  L('  Say "If the controller was off, just start it: it scans the tailnet and"');
  L('  Say "will find this machine by itself."');
  L('}');
  L('Say ("log file: " + $ProgressFile)');

  return lines.join('\r\n') + '\r\n';
}

/**
 * 检查生成的脚本是否是纯 ASCII。
 *
 * 生成端必须自己验证，不能指望调用方。PowerShell 5.1 读无 BOM 文件时按
 * GBK 解码，一个多字节字符就可能让下一行代码静默失效——这种 bug 在
 * 目标机器上表现为"某一步没生效"，极难排查。
 *
 * @returns {{ok:boolean, badIndex?:number, char?:string}}
 */
export function assertAscii(script) {
  for (let i = 0; i < script.length; i++) {
    const c = script.charCodeAt(i);
    if (c > 127) {
      return { ok: false, badIndex: i, char: String.fromCharCode(c) };
    }
  }
  return { ok: true };
}
