// super-subagent —— 被控端引导脚本生成
//
// 这段脚本解决了什么问题
//   原本要把一台机器变成子代理，得手工做六件事：装 Node、装 OpenSSH
//   Server、装 Tailscale、登录 Tailscale、把控制端公钥写进
//   authorized_keys、把 sshd 绑到 tailnet 地址。任何一步漏掉都表现为
//   「连不上」，而且没有提示。
//
//   现在这些全部由生成出来的一段脚本完成，最后自动向控制端报名。
//
// 为什么在控制端生成、而不是发一个固定的脚本
//   脚本里必须写死三样只在控制端才知道的东西：
//     - 控制端的 tailnet 地址和报名端口
//     - 本次报名用的令牌
//     - 控制端公钥（写进对方 authorized_keys）
//   所以只能现生成。这也顺带保证了令牌不会长期躺在某个公共文件里。
//
// 纯 ASCII 的硬约束
//   PowerShell 5.1 按 GBK 读无 BOM 的 .ps1；脚本里出现任何多字节字符
//   都可能造成语法错误（实测过：注释里的中文会吞掉后面的换行，
//   导致紧跟着的一行代码静默失效）。所以这里输出的正文全英文。

import { buildHealScript, buildRegisterTaskScript } from './selfheal.mjs';

/** 生成的脚本开头都带这一行，便于人工确认来源与时间。 */
const BANNER = '# Generated by super-subagent -- agent bootstrap';

/**
 * 估算一段脚本将来需要多少空间。仅用于界面上给个预期，不参与逻辑。
 */
export function estimateDuration() {
  return { minMinutes: 4, maxMinutes: 12 };
}

/**
 * 生成引导脚本。
 *
 * @param {object} opts
 * @param {string} opts.controllerIp     控制端 tailnet IPv4
 * @param {number} opts.beaconPort       控制端报名端口
 * @param {string} opts.token            本次报名令牌
 * @param {string} opts.controllerPubKey 控制端公钥（整行）
 * @param {string} [opts.agentName]      期望的设备名（默认取对方主机名）
 * @param {number} [opts.sshPort]        sshd 端口，默认 22
 * @param {string} [opts.tailscaleAuthKey] 可选：预授权 key，免去交互登录
 * @param {boolean} [opts.allowAnyTailnet] 是否同时允许 tailnet 内任意来源
 * @returns {string} 完整的 PowerShell 脚本（纯 ASCII）
 */
export function buildAgentScript({
  controllerIp,
  beaconPort,
  token,
  controllerPubKey,
  agentName = '',
  sshPort = 22,
  tailscaleAuthKey = '',
  section = '',
}) {
  // --- 参数校验。生成一份跑不通的脚本比不生成更糟。 ---
  //
  // 注意 IPv4 校验不能只数点：`999.1.1.1` 有四段数字，但每一段都必须是
  // 0-255。正则放行非法地址会在目标机器上变成 sshd 绑不上一个不存在
  // 的地址，然后静默退出——正是我们最想避免的那种失败。
  const ipOk =
    /^\d{1,3}(\.\d{1,3}){3}$/.test(String(controllerIp || '')) &&
    String(controllerIp)
      .split('.')
      .every((o) => Number(o) >= 0 && Number(o) <= 255);
  if (!ipOk) {
    throw new Error('控制器 IPv4 不合法: ' + controllerIp);
  }
  if (!Number.isInteger(beaconPort) || beaconPort < 1 || beaconPort > 65535) {
    throw new Error('报名端口不合法: ' + beaconPort);
  }
  if (!token || !/^fb_[A-Za-z0-9_-]{20,}$/.test(token)) {
    throw new Error('报名令牌格式不对（应以 fb_ 开头）');
  }
  if (!/^ssh-(ed25519|rsa|ecdsa)\s+AAAA/.test(String(controllerPubKey || ''))) {
    throw new Error('控制器公钥格式不对: ' + String(controllerPubKey).slice(0, 40));
  }
  if (!Number.isInteger(sshPort) || sshPort < 1 || sshPort > 65535) {
    throw new Error('SSH 端口不合法: ' + sshPort);
  }

  // 单引号里的内容会原样进入 PowerShell 字符串，必须转义单引号本身。
  const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

  // 自愈脚本以 base64 内嵌。
  //
  // 为什么不直接内联成 PowerShell 代码：它本身是一份完整的脚本（有函数、
  // 有 try/catch、有自己的 $ErrorActionPreference），拼进另一个脚本里很
  // 容易出现作用域和引号问题。base64 传字节，写盘后单独执行，边界最干净。
  const healScriptB64 = Buffer.from(buildHealScript({ sshPort }), 'utf8').toString('base64');
  const registerTaskB64 = Buffer.from(
    buildRegisterTaskScript({ healScriptPath: 'C:\\ProgramData\\super-subagent\\sshd-heal.ps1', sshPort }),
    'utf8',
  ).toString('base64');

  const lines = [];
  const L = (s = '') => lines.push(s);

  L(BANNER);
  L('#');
  L('# WHAT THIS DOES');
  L('#   1. checks/installs Node.js 18+');
  L('#   2. checks/installs the OpenSSH Server');
  L('#   3. checks/installs Tailscale, then waits for it to come up');
  L('#   4. writes the controller public key into authorized_keys');
  L('#   5. binds sshd to the Tailscale address only (never the company LAN)');
  L('#   6. reports itself back to the controller');
  L('#');
  L('# SAFETY');
  L('#   - port 22 is never opened to the local network; the firewall rule');
  L('#     is scoped to the Tailscale interface and 100.64.0.0/10');
  L('#   - password auth stays disabled; keys only');
  L('#   - nothing here touches project files or installed applications');
  L('#   - every step is idempotent: running it twice changes nothing');
  L('#');
  L('# RUN (elevated PowerShell). The -File form bypasses the execution policy');
  L('# for this one call only; without it Windows refuses to run any .ps1.');
  L('# Note the leading "&" and quotes: "$env:TEMP\\x.ps1" on its own is not a');
  L('# valid command, PowerShell stops at $env:TEMP and reports an unexpected');
  L('# token. Measured on a clean Windows 11 guest.');
  L('#   powershell -ep bypass -f .\\setup-agent.ps1');
  L('#   & "$env:TEMP\\setup-agent.ps1"');
  L('');
  L('$ErrorActionPreference = ' + q('Stop'));
  L('');
  L('# ---- configuration baked in by the controller ----');
  L('$ControllerIp   = ' + q(controllerIp));
  L('$BeaconPort     = ' + beaconPort);
  L('$BeaconToken    = ' + q(token));
  L('$SshPort        = ' + sshPort);
  L('$AgentName      = ' + q(agentName));
  L('$TailscaleAuthKey = ' + q(tailscaleAuthKey));
  if (section) {
    L('# Controller-supplied section label (display only).');
    L('$Section = ' + q(section));
  }
  L('');
  L('# The controller public key. Written verbatim into authorized_keys,');
  L('# with restrictions so a stolen key cannot open a shell or forward ports.');
  L('$ControllerPubKey = @' + "'");
  L(controllerPubKey.trim());
  L("'@");
  L('');
  L('# ---- progress log. Written next to the script so the user can send it back. ----');
  L('$ProgressFile = Join-Path $env:TEMP "super-subagent-setup.log"');
  L('function Say([string]$m) {');
  L('  $line = "[{0}] {1}" -f (Get-Date -Format "HH:mm:ss"), $m');
  L('  Write-Host $line');
  L('  try { Add-Content -Path $ProgressFile -Value $line -Encoding UTF8 -ErrorAction SilentlyContinue } catch { }');
  L('}');
  L('function Fail([string]$m) {');
  L('  Say ("FAILED: " + $m)');
  L('  Say "See the log above. Nothing was left half-configured on purpose."');
  L('  exit 1');
  L('}');
  L('');
  L('# External tools write progress and warnings to stderr. Under');
  L('# ErrorActionPreference=Stop, PowerShell turns each stderr line into a');
  L('# terminating ErrorRecord -- even when the output is only assigned to a');
  L('# variable. Measured: npm printing "warn EBADENGINE" killed the whole run.');
  L('# So every external call lowers the preference for its own duration and is');
  L('# judged by its exit code plus a real post-condition check instead.');
  L('#');
  L('# Every call is bounded by a timeout. This is not defensive padding:');
  L('# "Add-WindowsCapability -Online -Name OpenSSH.Server" measured 16 minutes');
  L('# on a guest that could not reach the Windows Update endpoints, with no');
  L('# output the whole time, and the script had no way to give up. An unbounded');
  L('# external call turns one unavailable service into a permanently hung');
  L('# installer that looks like a freeze rather than an error.');
  L('#');
  L('# Implementation note: this runs the command in a background job, not');
  L('# inline. An inline "& $exe @args" cannot be interrupted by any timer, and');
  L('# ProcessStartInfo on PowerShell 5.1 (.NET Framework) has no ArgumentList');
  L('# property to hand the array to (verified: PSObject.Properties reports');
  L('# False on 5.1.22621), so rebuilding a quoted command line by hand would be');
  L('# the only inline option -- and a quoting mistake there silently mangles');
  L('# arguments instead of failing loudly. A job hands the array back to');
  L('# PowerShell itself, which quotes correctly by construction, and can be');
  L('# stopped at the deadline.');
  L('#');
  L('# Code is null on timeout so callers can tell "the tool said no" from');
  L('# "the tool never answered"; those need different advice.');
  L('function Invoke-External {');
  L('  param([string]$FilePath, [string[]]$ArgumentList = @(), [int]$TimeoutSec = 300)');
  L('  $job = Start-Job -ScriptBlock {');
  L('    param($exe, $argv)');
  L('    $prev = $ErrorActionPreference');
  L('    $ErrorActionPreference = ' + q('Continue'));
  L('    try {');
  L('      $out = & $exe @argv 2>&1');
  L('      $out | ForEach-Object { "$_" }');
  L('      "###EXIT###=$LASTEXITCODE"');
  L('    } finally { $ErrorActionPreference = $prev }');
  L('  } -ArgumentList $FilePath, (,$ArgumentList)');
  L('  $done = Wait-Job -Job $job -Timeout $TimeoutSec');
  L('  if (-not $done) {');
  L('    # Kill before reporting, otherwise a retry races the orphaned process');
  L('    # for the same service, port or file.');
  L('    Stop-Job -Job $job -ErrorAction SilentlyContinue');
  L('    Remove-Job -Job $job -Force -ErrorAction SilentlyContinue');
  L('    return @{ Code = $null; TimedOut = $true; Text = ("timed out after " + $TimeoutSec + "s") }');
  L('  }');
  L('  $lines = @(Receive-Job -Job $job -ErrorAction SilentlyContinue)');
  L('  Remove-Job -Job $job -Force -ErrorAction SilentlyContinue');
  L('  $code = $null');
  L('  $body = New-Object System.Collections.ArrayList');
  L('  foreach ($ln in $lines) {');
  L('    $s = "$ln"');
  L('    if ($s -match ' + q('^###EXIT###=(-?\\d+)$') + ') { $code = [int]$Matches[1]; continue }');
  L('    [void]$body.Add($s)');
  L('  }');
  L('  return @{ Code = $code; TimedOut = $false; Text = (($body -join "`r`n").Trim()) }');
  L('}');
  L('');
  L('function Test-Admin {');
  L('  $id = [Security.Principal.WindowsIdentity]::GetCurrent()');
  L('  $p = New-Object Security.Principal.WindowsPrincipal($id)');
  L('  return $p.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)');
  L('}');
  L('');
  L('Say "=== super-subagent agent setup ==="');
  L('Say ("controller: " + $ControllerIp + ":" + $BeaconPort)');
  L('');
  L('if (-not (Test-Admin)) {');
  L('  Fail "must run in an elevated PowerShell (right-click > Run as administrator)"');
  L('}');
  L('Say "running elevated: yes"');
  L('');

  // --- step 1: node ---
  L('# =====================================================================');
  L('# STEP 1/6  Node.js');
  L('# =====================================================================');
  L('Say ""');
  L('Say "--- step 1/6: Node.js ---"');
  L('$node = Get-Command node -ErrorAction SilentlyContinue');
  L('# A fresh machine has no nodejs on PATH yet even right after installing it,');
  L('# so also probe the usual install locations before deciding to install.');
  L('if (-not $node) {');
  L('  foreach ($cand in @("$env:ProgramFiles\\nodejs\\node.exe", "${env:ProgramFiles(x86)}\\nodejs\\node.exe", "$env:LOCALAPPDATA\\Programs\\nodejs\\node.exe")) {');
  L('    if (Test-Path $cand) { $node = @{ Source = $cand }; break }');
  L('  }');
  L('}');
  L('if ($node) {');
  L('  $v = (& $node.Source --version) 2>&1');
  L('  Say ("node already present: " + $v)');
  L('} else {');
  L('  Say "node not found; installing Node.js LTS via winget"');
  L('  $w = Get-Command winget -ErrorAction SilentlyContinue');
  L('  if (-not $w) { Fail "winget not available; install Node.js 18+ manually, then re-run" }');
  L('  $r = Invoke-External winget @("install", "--id", "OpenJS.NodeJS.LTS", "--silent", "--accept-package-agreements", "--accept-source-agreements")');
  L('  if ($r.Code -ne 0) { Say $r.Text; Fail "winget could not install Node.js" }');
  L('  foreach ($cand in @("$env:ProgramFiles\\nodejs\\node.exe", "$env:LOCALAPPDATA\\Programs\\nodejs\\node.exe")) {');
  L('    if (Test-Path $cand) { $node = @{ Source = $cand }; break }');
  L('  }');
  L('  if (-not $node) { Fail "Node.js installed but the executable cannot be found" }');
  L('  Say "node installed"');
  L('}');
  L('');

  // --- step 2: sshd ---
  L('# =====================================================================');
  L('# STEP 2/6  OpenSSH Server');
  L('# =====================================================================');
  L('Say "--- step 2/6: OpenSSH Server ---"');
  L('# sshd.exe can end up in three places depending on how it was installed:');
  L('#   - the Windows capability  -> System32\\OpenSSH');
  L('#   - the Win32-OpenSSH MSI   -> Program Files\\OpenSSH');
  L('#   - winget Microsoft.OpenSSH.Preview -> either of the above');
  L('# Probe all of them instead of assuming one, and do it before deciding to');
  L('# install: a half-installed capability leaves the service absent while the');
  L('# binaries are already on disk, and reinstalling over that wastes minutes.');
  L('# Prefer whatever path the service is ALREADY registered against. That is');
  L('# the binary Windows will actually launch, so validating or configuring a');
  L('# different copy is how you end up proving the config is fine while the');
  L('# service refuses to start. Measured on a guest where both');
  L('# System32\OpenSSH\sshd.exe (the built-in 9.5) and a winget-installed copy');
  L('# existed: probing System32 first silently configured the built-in one.');
  L('$sshdExe = ""');
  L('try {');
  L('  $reg = (Get-CimInstance Win32_Service -Filter ' + q("Name='sshd'") + ' -ErrorAction Stop).PathName');
  L('  if ($reg) {');
  L('# PathName comes back quoted, often with trailing arguments.');
  L('    $regExe = $reg.Trim()');
  L('    if ($regExe.StartsWith([char]34)) {');
  L('      $close = $regExe.IndexOf([char]34, 1)');
  L('      if ($close -gt 1) { $regExe = $regExe.Substring(1, $close - 1) }');
  L('    } else {');
  L('      $regExe = ($regExe -split ' + q(' ') + ')[0]');
  L('    }');
  L('    if ($regExe -and (Test-Path $regExe)) { $sshdExe = $regExe }');
  L('  }');
  L('} catch { }');
  L('if (-not $sshdExe) {');
  L('# Not registered yet: fall back to the usual install layouts. The MSI');
  L('# location is tried before the built-in one because a winget install is');
  L('# the common case on a fresh machine and is the more complete build.');
  L('  $sshdCandidates = @(');
  L('    "$env:ProgramFiles\\OpenSSH\\sshd.exe",');
  L('    "$env:ProgramFiles\\OpenSSH-Win64\\sshd.exe",');
  L('    "${env:ProgramFiles(x86)}\\OpenSSH\\sshd.exe",');
  L('    "$env:SystemRoot\\System32\\OpenSSH\\sshd.exe"');
  L('  )');
  L('  foreach ($cand in $sshdCandidates) { if (Test-Path $cand) { $sshdExe = $cand; break } }');
  L('}');
  L('# Even when a copy is on disk, the service may reference a different or');
  L('# broken path, so fall back to a known-good binary if the registered one');
  L('# is unusable.');
  L('$sshdSvc = Get-Service sshd -ErrorAction SilentlyContinue');
  L('');
  L('if ($sshdExe) {');
  L('  Say ("sshd already on disk: " + $sshdExe)');
  L('} else {');
  L('# winget first, the capability second. The capability resolves through');
  L('# Windows Update, which measured 16 minutes of silence on a guest that');
  L('# could not reach those endpoints -- and then failed. winget pulls the MSI');
  L('# straight from the vendor CDN and measured about one minute on the same');
  L('# guest. Try the fast path that actually works first.');
  L('  $installed = $false');
  L('  $w = Get-Command winget -ErrorAction SilentlyContinue');
  L('  if ($w) {');
  L('    Say "installing OpenSSH Server via winget"');
  L('    $r = Invoke-External winget @("install", "--id", "Microsoft.OpenSSH.Preview", "--silent", "--accept-package-agreements", "--accept-source-agreements") -TimeoutSec 300');
  L('    if ($r.TimedOut) { Say "winget timed out; falling back to the Windows capability" }');
  L('    foreach ($cand in $sshdCandidates) { if (Test-Path $cand) { $sshdExe = $cand; $installed = $true; break } }');
  L('    if (-not $installed) { Say ("winget did not leave sshd.exe behind: " + $r.Text) }');
  L('  }');
  L('');
  L('  if (-not $installed) {');
  L('    Say "installing the OpenSSH Server capability"');
  L('    # Bounded: on a guest that cannot reach Windows Update this never returns.');
  L('    $capArgs = "Add-WindowsCapability -Online -Name OpenSSH.Server~~~~0.0.1.0"');
  L('    $r = Invoke-External powershell @("-NoProfile", "-NonInteractive", "-Command", $capArgs) -TimeoutSec 240');
  L('    if ($r.TimedOut) {');
  L('      Fail ("the Windows capability install did not finish in 4 minutes. " +');
  L('            "That path needs reachable Windows Update endpoints. Install OpenSSH " +');
  L('            "manually -- open Settings > System > Optional features > Add a feature > " +');
  L('            "OpenSSH Server, or run: winget install --id Microsoft.OpenSSH.Preview " +');
  L('            "-- then re-run this script.")');
  L('    }');
  L('    foreach ($cand in $sshdCandidates) { if (Test-Path $cand) { $sshdExe = $cand; break } }');
  L('  }');
  L('}');
  L('');
  L('if (-not $sshdExe) {');
  L('  Fail ("OpenSSH server is not installed and could not be installed. Install it " +');
  L('        "with: winget install --id Microsoft.OpenSSH.Preview -- then re-run this " +');
  L('        "script. Nothing else was changed.")');
  L('}');
  L('Say ("sshd.exe: " + $sshdExe)');
  L('');
  L('# The MSI and the capability both need the service registered; the MSI can');
  L('# leave sshd.exe on disk without the service when run non-interactively.');
  L('#');
  L('# An EXISTING registration is not proof of a WORKING one. sc create can');
  L('# register an entry that sc query reports as healthy and that nevertheless');
  L('# fails to start with ERROR_INVALID_PARAMETER. So probe the presence AND');
  L('# the shape of the entry, and re-register when either is wrong; otherwise a');
  L('# machine is left permanently unstartable and every later run skips the fix.');
  L('$sshdSvc = Get-Service sshd -ErrorAction SilentlyContinue');
  L('$svcBroken = $false');
  L('if ($sshdSvc) {');
  L('# The image path must exist, and it must actually be a path (an empty or');
  L('# relative value is what a malformed registration leaves behind).');
  L('  $imgPath = ""');
  L('  try { $imgPath = (Get-CimInstance Win32_Service -Filter ' + q("Name='sshd'") + ' -ErrorAction Stop).PathName } catch { }');
  L('  if (-not $imgPath) {');
  L('    Say "sshd service is registered but has no image path; re-registering"');
  L('    $svcBroken = $true');
  L('  } elseif (-not (Test-Path $sshdExe)) {');
  L('    Say ("sshd service points at " + $sshdExe + " which does not exist; re-registering")');
  L('    $svcBroken = $true');
  L('  }');
  L('}');
  L('if ($svcBroken) {');
  L('  $r = Invoke-External sc.exe @("delete", "sshd") -TimeoutSec 60');
  L('  if ($r.Code -ne 0) { Say ("warning: could not delete the broken service: " + $r.Text) }');
  L('  $sshdSvc = $null');
  L('}');
  L('if (-not $sshdSvc) {');
  L('  Say "sshd service not registered; registering it"');
  L('  $sshdDir = Split-Path -Parent $sshdExe');
  L('  $keygen = Join-Path $sshdDir "ssh-keygen.exe"');
  L('  if (Test-Path $keygen) {');
  L('    $r = Invoke-External $keygen @("-A") -TimeoutSec 120');
  L('    if ($r.Code -ne 0) { Say ("host key generation returned " + $r.Code + ": " + $r.Text) }');
  L('  }');
  L('  # Register with New-Service, NOT sc.exe create. sc.exe parses its own');
  L('  # command line and needs "start=" and "auto" as ONE token; handed an');
  L('  # array it splits them, and it then registers a service that sc query');
  L('  # reports as perfectly normal -- correct image path, AUTO_START,');
  L('  # LocalSystem -- but that fails to start with ERROR_INVALID_PARAMETER');
  L('  # (87) and a system log line saying only "the service failed to start".');
  L('  # Measured on a guest: sc create, never startable; delete and re-register');
  L('  # with New-Service, starts immediately. The failure is in the registry');
  L('  # entry, so no amount of checking sshd_config or host keys can find it.');
  L('  #');
  L('  # The config path goes in the service command line too, so the service');
  L('  # does not depend on sshd\'s compiled-in default location.');
  L('  $svcCmd = [char]34 + $sshdExe + [char]34 + " -f " + [char]34 + "C:\\ProgramData\\ssh\\sshd_config" + [char]34');
  L('  $r = Invoke-External powershell @("-NoProfile", "-NonInteractive", "-Command",');
  L('        ("New-Service -Name sshd -BinaryPathName " + [char]39 + $svcCmd + [char]39 + " -StartupType Automatic -ErrorAction Stop")) -TimeoutSec 90');
  L('  if ($r.Code -ne 0) {');
  L('# Do not limp on: the restart in step 5 would fail with a confusing');
  L('# "cannot open service" and the user would have no idea what to fix.');
  L('    Say ("sc create failed: " + $r.Text)');
  L('    Fail ("sshd.exe is on disk at " + $sshdExe + " but the sshd service could not be " +');
  L('          "registered (sc.exe exit " + $r.Code + "). This usually means the OpenSSH " +');
  L('          "install is incomplete. Reinstall it with: winget install --id " +');
  L('          "Microsoft.OpenSSH.Preview --force -- then re-run this script. " +');
  L('          "Nothing else was changed.")');
  L('  }');
  L('  $sshdSvc = Get-Service sshd -ErrorAction SilentlyContinue');
  L('  if (-not $sshdSvc) { Fail "sc create reported success but the sshd service is still absent" }');
  L('  Say "sshd service registered"');
  L('}');
  L('');

  // --- step 3: tailscale ---
  L('# =====================================================================');
  L('# STEP 3/6  Tailscale');
  L('# =====================================================================');
  L('Say "--- step 3/6: Tailscale ---"');
  L('$tsExe = "C:\\Program Files\\Tailscale\\tailscale.exe"');
  L('if (-not (Test-Path $tsExe)) {');
  L('  Say "installing Tailscale"');
  L('  $w = Get-Command winget -ErrorAction SilentlyContinue');
  L('  if ($w) {');
  L('    $r = Invoke-External winget @("install", "--id", "Tailscale.Tailscale", "--silent", "--accept-package-agreements", "--accept-source-agreements")');
  L('    if ($r.Code -ne 0) { Say $r.Text }');
  L('  }');
  L('  if (-not (Test-Path $tsExe)) { Fail "Tailscale not installed; get it from https://tailscale.com/download/windows" }');
  L('  Say "Tailscale installed"');
  L('} else { Say "Tailscale already installed" }');
  L('');
  L('# Wait for a tailnet address. Right after a fresh install or a reinstall,');
  L('# tailscaled has no node key yet and only allocates an address after login.');
  L('# Binding sshd before that point is exactly what locks this design out, so');
  L('# never proceed without a real IPv4.');
  L('#');
  L('# Whatever happens here, never leave the user staring at a frozen window.');
  L('# "tailscale up" without an auth key prints a URL and then blocks until');
  L('# somebody opens it -- measured 33 minutes with no further output, which');
  L('# reads as a hang rather than as "go approve this in a browser". The call');
  L('# below is therefore bounded, and the copy says what to do next.');
  L('function Get-TsIp {');
  L('  $cand = ""');
  L('  try { $cand = ((& $tsExe ip -4) 2>&1 | Out-String).Trim() } catch { }');
  L('  if ($cand -match "^\\d{1,3}(\\.\\d{1,3}){3}$") { return $cand }');
  L('  return ""');
  L('}');
  L('');
  L('$tsIp = Get-TsIp');
  L('if ($tsIp) {');
  L('  Say ("Tailscale already logged in: " + $tsIp)');
  L('}');
  L('');
  L('if (-not $tsIp -and $TailscaleAuthKey) {');
  L('  Say "logging in with the supplied auth key"');
  L('  $r = Invoke-External $tsExe @("up", "--authkey", $TailscaleAuthKey, "--accept-routes=false") -TimeoutSec 180');
  L('  if ($r.TimedOut) { Say "tailscale up timed out with the auth key" }');
  L('  elseif ($r.Code -ne 0) { Say ("auth key login returned " + $r.Code + ": " + $r.Text) }');
  L('  $tsIp = Get-TsIp');
  L('}');
  L('');
  L('if (-not $tsIp) {');
  L('  # Interactive login. The URL is printed by tailscale itself and is the');
  L('  # ONLY way forward without an auth key, so surface it prominently and');
  L('  # tell the user it can be opened on a different machine -- the approval');
  L('  # happens on the control plane, so the browser does not have to be here.');
  L('  Say ""');
  L('  Say "== Action needed: approve this machine in Tailscale =="');
  L('  Say "A URL is about to appear. Open it in any browser -- it does not have"');
  L('  Say "to be on this machine. Sign in with the SAME account the controller"');
  L('  Say "uses, then come back here. This script waits up to 10 minutes."');
  L('  Say ""');
  L('  $r = Invoke-External $tsExe @("up", "--accept-routes=false") -TimeoutSec 60');
  L('  if ($r.Text) { Say $r.Text }');
  L('# tailscale up blocks while holding the URL it printed, so this call is');
  L('# cut short on purpose; the login below polls for the result instead.');
  L('# --reset stops the flag-restatement error, which otherwise fails the');
  L('# login silently and sends the script into a blind wait.');
  L('  $r = Invoke-External $tsExe @("up", "--reset") -TimeoutSec 30');
  L('  if ($r.Text) { Say $r.Text }');
  L('');
  L('# Poll for up to 10 minutes, reporting state so the window is not silent.');
  L('  for ($i = 1; $i -le 60; $i++) {');
  L('    $tsIp = Get-TsIp');
  L('    if ($tsIp) { break }');
  L('    if ($i % 6 -eq 0) {');
  L('      $st = ""');
  L('      try { $st = ((& $tsExe status 2>&1 | Out-String).Trim()) } catch { }');
  L('      if ($st -match ' + q('(?m)^\\s*(Logged out|NeedsLogin)') + ') {');
  L('        Say ("still " + $Matches[1] + " after " + ($i * 10) + "s -- open a browser and approve the login")');
  L('      } else {');
  L('        Say ("still waiting for an address after " + ($i * 10) + "s")');
  L('      }');
  L('    }');
  L('    Start-Sleep -Seconds 10');
  L('  }');
  L('}');
  L('');
  L('if (-not $tsIp) {');
  L('  Fail ("no Tailscale address. This machine is not logged in to the tailnet. " +');
  L('        "Fix it in this window: run [tailscale up] and open the URL it prints, " +');
  L('        "OR generate an auth key at https://login.tailscale.com/admin/settings/keys " +');
  L('        "and re-run this script from the controller panel with that key filled in. " +');
  L('        "Nothing else was changed.")');
  L('}');
  L('Say ("tailscale address: " + $tsIp)');
  L('');

  // --- step 4: authorized_keys ---
  L('# =====================================================================');
  L('# STEP 4/6  Authorize the controller key');
  L('# =====================================================================');
  L('Say "--- step 4/6: authorize the controller ---"');
  L('# Windows OpenSSH splits this by account type and the split is the single');
  L('# most common reason a key silently does not work:');
  L('#   - an ADMIN account is validated against');
  L('#     C:\\ProgramData\\ssh\\administrators_authorized_keys (shared by all admins)');
  L('#   - a STANDARD account is validated against');
  L('#     C:\\Users\\<name>\\.ssh\\authorized_keys');
  L('# Which one applies is decided by the account sshd logs in as, not by the');
  L('# account running this script. We cannot know which account the controller');
  L('# will use, so authorize BOTH and let sshd pick. Writing only one is how a');
  L('# correctly-signed key still yields "Permission denied (publickey)".');
  L('#');
  L('# Every account that could plausibly be the login target gets the key: all');
  L('# local administrators, plus the account that ran this script.');
  L('# The key is written with the "restrict" option, not bare. restrict is an');
  L('# OpenSSH authorized_keys flag that turns off EVERY optional feature for');
  L('# that key at once: no agent forwarding, no TCP forwarding, no pty, no');
  L('# X11, no port forwarding, no user rc. Verified against a live guest -- a');
  L('# bare key happily opened -L tunnels and allocated a pty, which means the');
  L('# controller credential was also a general-purpose remote shell.');
  L('#');
  L('# The fleet only ever needs to run commands over this channel, so nothing');
  L('# is lost, and a stolen key cannot be used to pivot through the machine.');
  L('$keyLine = "restrict " + $ControllerPubKey.Trim()');
  L('');
  L('function Add-AuthorizedKey {');
  L('  param([string]$Path)');
  L('  $dir = Split-Path -Parent $Path');
  L('  if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }');
  L('  $have = @()');
  L('  if (Test-Path $Path) { $have = @(Get-Content $Path -ErrorAction SilentlyContinue) }');
  L('# Compare on the public key itself, not the whole line. An earlier version');
  L('# wrote this key WITHOUT restrict, so matching the full line would leave');
  L('# that unrestricted key in place forever and report "already present".');
  L('  $id = ($ControllerPubKey.Trim() -split " ")[0..1] -join " "');
  L('  $idx = -1');
  L('  for ($i = 0; $i -lt $have.Count; $i++) {');
  L('    $ln = "$($have[$i])".Trim()');
  L('    if (-not $ln) { continue }');
  L('# -like, not a regex: the key body is base64 and contains +/ characters,');
  L('# which a hand-written regex escape would get wrong.');
  L('    if ($ln -like ("*" + $id + "*")) { $idx = $i; break }');
  L('  }');
  L('  if ($idx -lt 0) {');
  L('    Add-Content -Path $Path -Value $keyLine -Encoding ASCII');
  L('    Say ("key written to " + $Path)');
  L('  } elseif ($have[$idx].Trim() -eq $keyLine) {');
  L('    Say ("key already present in " + $Path)');
  L('  } else {');
  L('# Present but without the restrictions: upgrade the line in place rather');
  L('# than appending a duplicate, which sshd would treat as a second key.');
  L('    $have[$idx] = $keyLine');
  L('    Set-Content -Path $Path -Value $have -Encoding ASCII');
  L('    Say ("key upgraded to restricted in " + $Path)');
  L('  }');
  L('}');
  L('');
  L('# 1. the all-administrators file');
  L('$adminFile = "C:\\ProgramData\\ssh\\administrators_authorized_keys"');
  L('Add-AuthorizedKey $adminFile');
  L('# sshd refuses this file when other users can write to it.');
  L('$r = Invoke-External icacls @($adminFile, "/inheritance:r", "/grant", "Administrators:F", "/grant", "SYSTEM:F") -TimeoutSec 60');
  L('if ($r.Code -ne 0) { Say ("warning: could not tighten ACLs on " + $adminFile + ": " + $r.Text) }');
  L('');
  L('# 2. the per-user file for every local administrator and for the caller.');
  L('#    A standard account is only ever checked against its own profile file,');
  L('#    so a standard-account target is unreachable without this.');
  L('$targets = New-Object System.Collections.ArrayList');
  L('try {');
  L('  $admins = Get-LocalGroupMember -Group "Administrators" -ErrorAction Stop');
  L('  foreach ($m in $admins) {');
  L('    if ($m.Name -match "\\\\(.+)$") { [void]$targets.Add($Matches[1]) }');
  L('  }');
  L('} catch { Say ("could not enumerate administrators: " + $_.Exception.Message) }');
  L('foreach ($u in @($env:USERNAME, $env:USERPROFILE.Split("\\")[-1])) {');
  L('  if ($u -and -not ($targets -contains $u)) { [void]$targets.Add($u) }');
  L('}');
  L('foreach ($u in ($targets | Select-Object -Unique)) {');
  L('  if (-not $u) { continue }');
  L('  if ($u -match "^(Administrator|DefaultAccount|WDAGUtilityAccount|system)$") { continue }');
  L('  $profileDir = Join-Path "C:\\Users" $u');
  L('  if (-not (Test-Path $profileDir)) { continue }');
  L('  $uFile = Join-Path (Join-Path $profileDir ".ssh") "authorized_keys"');
  L('  Add-AuthorizedKey $uFile');
  L('  # sshd runs as SYSTEM and reads this file as SYSTEM, so granted read is');
  L('  # enough; leaving inheritance on prevents an unreadable-file failure.');
  L('  $r = Invoke-External icacls @($uFile, "/inheritance:r", "/grant", "SYSTEM:F", "/grant", "Administrators:F", "/grant", ($u + ":F")) -TimeoutSec 60');
  L('  if ($r.Code -ne 0) { Say ("warning: could not set ACLs on " + $uFile + ": " + $r.Text) }');
  L('}');
  L('');

  // --- step 5: bind sshd to tailnet ---
  L('# =====================================================================');
  L('# STEP 5/6  Bind sshd to the Tailscale address only');
  L('# =====================================================================');
  L('Say "--- step 5/6: harden sshd ---"');
  L('$cfg = "C:\\ProgramData\\ssh\\sshd_config"');
  L('if (-not (Test-Path $cfg)) {');
  L('# The default template lives next to sshd.exe, not always in System32: a');
  L('# winget/MSI install puts it under Program Files\\OpenSSH. Probe the');
  L('# directory sshd actually came from rather than one hardcoded path.');
  L('  $sshdDir = Split-Path -Parent $sshdExe');
  L('  foreach ($tpl in @((Join-Path $sshdDir "sshd_config_default"),');
  L('                     "$env:SystemRoot\\System32\\OpenSSH\\sshd_config_default")) {');
  L('    if (Test-Path $tpl) { Copy-Item $tpl $cfg -Force; break }');
  L('  }');
  L('}');
  L('if (-not (Test-Path $cfg)) {');
  L('# No template anywhere. A minimal config is better than failing here: the');
  L('# following block overwrites every directive that matters anyway.');
  L('  Say "no sshd_config template found; writing a minimal one"');
  L('  $sshDir = Split-Path -Parent $cfg');
  L('  if (-not (Test-Path $sshDir)) { New-Item -ItemType Directory -Path $sshDir -Force | Out-Null }');
  L('  Set-Content -Path $cfg -Value "# generated by super-subagent`r`n" -Encoding ASCII');
  L('}');
  L('$bak = "$cfg.subagent-bak"');
  L('if (-not (Test-Path $bak)) { Copy-Item $cfg $bak -Force }');
  L('');
  L('$text = Get-Content $cfg -Raw');
  L('# Only rewrite directives before the first Match block; they are illegal inside it.');
  L('$mi = [regex]::Match($text, "(?m)^[ \\t]*Match[ \\t]").Index');
  L('$head = if ($mi -ge 0) { $text.Substring(0, $mi) } else { $text }');
  L('$tail = if ($mi -ge 0) { $text.Substring($mi) } else { "" }');
  L('$head = [regex]::Replace($head, "(?m)^[ \\t]*#?[ \\t]*ListenAddress[^\\r\\n]*(?:\\r?\\n)?", "")');
  L('$head = [regex]::Replace($head, "(?m)^[ \\t]*#?[ \\t]*Port[ \\t]+\\d+[^\\r\\n]*(?:\\r?\\n)?", "")');
  L('$head = [regex]::Replace($head, "(?m)^[ \\t]*#?[ \\t]*PasswordAuthentication[^\\r\\n]*(?:\\r?\\n)?", "")');
  L('$head = $head.TrimEnd() + "`r`n"');
  L('$head += "Port $SshPort`r`n"');
  L('$head += "ListenAddress $tsIp`r`n"');
  L('$head += "ListenAddress 127.0.0.1`r`n"');
  L('$head += "PasswordAuthentication no`r`n"');
  L('$head += "PubkeyAuthentication yes`r`n"');
  L('Set-Content -Path $cfg -Value ($head + $tail) -Encoding ASCII -NoNewline');
  L('Say "sshd_config rewritten (backup at $bak)"');
  L('');
  L('# Validate BEFORE restarting. A broken config plus an aggressive restart');
  L('# policy once produced 2500 restarts in one second and no service at all.');
  L('$t = Invoke-External $sshdExe @("-t", "-f", $cfg)');
  L('if ($t.Code -ne 0) {');
  L('  Say $t.Text');
  L('  Copy-Item $bak $cfg -Force');
  L('  Fail "sshd_config failed validation; the previous config was restored"');
  L('}');
  L('Say "sshd_config is valid"');
  L('');
  L('# sshd must start after Tailscale, because it binds to the Tailscale');
  L('# address. Without this dependency it can start first, fail to bind, and die.');
  L('#');
  L('# But the dependency is only safe when the named service EXISTS. sc.exe');
  L('# accepts a dependency on a name that is not installed, and the SCM then');
  L('# refuses to start the dependent service forever after, with');
  L('# "the service could not be started on computer ." -- which names neither');
  L('# the dependency nor the fix. Measured: a guest whose tailscaled service');
  L('# was named differently ended up with an sshd that a valid config, working');
  L('# host keys and a free port could not start.');
  L('$tsSvcName = ""');
  L('foreach ($n in @("Tailscale", "tailscaled")) {');
  L('  if (Get-Service -Name $n -ErrorAction SilentlyContinue) { $tsSvcName = $n; break }');
  L('}');
  L('if ($tsSvcName) {');
  L('  $r = Invoke-External sc.exe @("config", "sshd", "depend=", $tsSvcName) -TimeoutSec 60');
  L('  if ($r.Code -ne 0) {');
  L('    Say ("sc config depend failed (exit " + $r.Code + "): " + $r.Text)');
  L('    Fail ("the sshd service is missing or inaccessible. Its binary is at " + $sshdExe +');
  L('          ". Reinstall OpenSSH with: winget install --id Microsoft.OpenSSH.Preview " +');
  L('          "--force -- then re-run this script. Nothing else was changed.")');
  L('  }');
  L('  Say ("sshd now depends on the " + $tsSvcName + " service")');
  L('} else {');
  L('# No Tailscale service to depend on. Do not invent one: a dependency on a');
  L('# service that is not installed makes sshd permanently unstartable. The');
  L('# boot-time self-healing task below is what covers this case instead.');
  L('  Say "no Tailscale service found; sshd will not declare a dependency"');
  L('# depend=/ is how sc.exe clears a dependency. "depend=" with no value is');
  L('# not an empty dependency: sc.exe prints its usage text, exits 0, and does');
  L('# nothing at all -- so a stale dependency silently survives.');
  L('  $r = Invoke-External sc.exe @("config", "sshd", "depend=/") -TimeoutSec 60');
  L('  if ($r.Code -ne 0) { Say ("warning: could not clear the sshd dependency: " + $r.Text) }');
  L('}');
  L('Set-Service sshd -StartupType Automatic -ErrorAction SilentlyContinue');
  L('# Restart after 60s, give up after 3 tries -- never the tight default loop.');
  L('$r = Invoke-External sc.exe @("failure", "sshd", "reset=", "86400", "actions=", "restart/60000/restart/60000/restart/60000") -TimeoutSec 60');
  L('if ($r.Code -ne 0) { Say ("warning: could not set the recovery policy: " + $r.Text) }');
  L('');
  L('# Before starting, clear anything already holding the port. A leftover sshd');
  L('# from an earlier install, or a manual "sshd -d" run left open in another');
  L('# window, makes the service fail with "the service could not be started on');
  L('# computer ." -- an error that mentions neither the port nor the squatter.');
  L('# Measured: a foreground sshd -d held 22 and the service refused to start.');
  L('$squatters = @(Get-Process sshd -ErrorAction SilentlyContinue)');
  L('if ($squatters.Count -gt 0) {');
  L('  Say ("stopping " + $squatters.Count + " existing sshd process(es) first")');
  L('  $squatters | ForEach-Object { try { Stop-Process -Id $_.Id -Force -ErrorAction Stop } catch { } }');
  L('# Give the socket time to be released; a restart immediately after the kill');
  L('# can still see the port as taken.');
  L('  for ($i = 1; $i -le 10; $i++) {');
  L('    $busy = @(Get-NetTCPConnection -LocalPort $SshPort -State Listen -ErrorAction SilentlyContinue)');
  L('    if ($busy.Count -eq 0) { break }');
  L('    Start-Sleep -Seconds 1');
  L('  }');
  L('}');
  L('');
  L('Try {');
  L('  Restart-Service sshd -Force -ErrorAction Stop');
  L('} Catch {');
  L('  Say ("restart failed: " + $_.Exception.Message)');
  L('# Diagnose instead of guessing. The generic failure text is identical for');
  L('# "port taken", "config rejected" and "binary missing", so check which one');
  L('# it actually is and say so.');
  L('  $busy = @(Get-NetTCPConnection -LocalPort $SshPort -State Listen -ErrorAction SilentlyContinue)');
  L('  if ($busy.Count -gt 0) {');
  L('    $who = ($busy | ForEach-Object { $_.LocalAddress + " pid=" + $_.OwningProcess }) -join ", "');
  L('    Fail ("something is still listening on port " + $SshPort + " (" + $who + "), so sshd " +');
  L('          "cannot bind it. Stop that process and re-run this script.")');
  L('  }');
  L('  $verify = Invoke-External $sshdExe @("-t", "-f", $cfg) -TimeoutSec 60');
  L('  if ($verify.Code -ne 0) {');
  L('    Say $verify.Text');
  L('    Fail ("the sshd configuration at " + $cfg + " is rejected by the binary at " +');
  L('          $sshdExe + ". Restore the backup at " + $bak + " and re-run.")');
  L('  }');
  L('# Config parses and the port is free, so the failure is in the service');
  L('# definition, and that is fully recoverable. Two causes, tried in order:');
  L('#   1. a dependency on a service that is not installed');
  L('#   2. a malformed registration (ERROR_INVALID_PARAMETER / start 87)');
  L('# Both are fixed in place. Sending the user off to reinstall OpenSSH for');
  L('# either one is a dead end: the binaries and the config are fine.');
  L('  $recovered = $false');
  L('  $dep = ""');
  L('  try {');
  L('    $svcDef = Get-CimInstance Win32_Service -Filter ' + q("Name='sshd'") + ' -ErrorAction Stop');
  L('    if ($svcDef.ServicesDependedOn) { $dep = ($svcDef.ServicesDependedOn -join ",") }');
  L('  } catch { }');
  L('  if ($dep) {');
  L('    Say ("sshd declares a dependency on: " + $dep + " -- retrying without it")');
  L('    $clr = Invoke-External sc.exe @("config", "sshd", "depend=/") -TimeoutSec 60');
  L('    if ($clr.Code -ne 0) { Say ("could not clear the dependency: " + $clr.Text) }');
  L('    Try {');
  L('      Restart-Service sshd -Force -ErrorAction Stop');
  L('      Start-Sleep -Seconds 3');
  L('      $svc = Get-Service sshd -ErrorAction SilentlyContinue');
  L('      if ($svc -and $svc.Status -eq "Running") {');
  L('        Say "sshd started after the dependency was cleared"');
  L('        $recovered = $true');
  L('      }');
  L('    } Catch { Say ("retry without the dependency also failed: " + $_.Exception.Message) }');
  L('  }');
  L('');
  L('  if (-not $recovered) {');
  L('# The registration itself is malformed. Re-create it from scratch with');
  L('# New-Service, which is the form that actually starts.');
  L('    Say "the sshd registration is malformed; re-creating it"');
  L('    $del = Invoke-External sc.exe @("delete", "sshd") -TimeoutSec 60');
  L('    if ($del.Code -ne 0) { Say ("could not delete the service: " + $del.Text) }');
  L('    Start-Sleep -Seconds 1');
  L('    $svcCmd2 = [char]34 + $sshdExe + [char]34 + " -f " + [char]34 + $cfg + [char]34');
  L('    $mk = Invoke-External powershell @("-NoProfile", "-NonInteractive", "-Command",');
  L('          ("New-Service -Name sshd -BinaryPathName " + [char]39 + $svcCmd2 + [char]39 + " -StartupType Automatic -ErrorAction Stop")) -TimeoutSec 90');
  L('    if ($mk.Code -eq 0) {');
  L('      Try {');
  L('        Start-Service sshd -ErrorAction Stop');
  L('        Start-Sleep -Seconds 3');
  L('        $svc = Get-Service sshd -ErrorAction SilentlyContinue');
  L('        if ($svc -and $svc.Status -eq "Running") {');
  L('          Say "sshd started after being re-registered"');
  L('          $recovered = $true');
  L('        }');
  L('      } Catch { Say ("start after re-registering failed: " + $_.Exception.Message) }');
  L('    } else { Say ("could not re-register the service: " + $mk.Text) }');
  L('  }');
  L('# Show what the service actually points at before giving up.');
  L('  if (-not $recovered) {');
  L('    $qc = Invoke-External sc.exe @("qc", "sshd") -TimeoutSec 60');
  L('    if ($qc.Text) { Say $qc.Text }');
  L('    Fail ("sshd will not start and the config is valid. The service definition " +');
  L('          "is printed above; compare BINARY_PATH_NAME with " + $sshdExe + ". " +');
  L('          "Reinstall with: winget install --id Microsoft.OpenSSH.Preview --force")');
  L('  }');
  L('}');
  L('# Poll instead of a single sleep. sshd forks and only binds its listeners');
  L('# a moment later; a fixed 4s wait passed on one run and failed the next.');
  L('$svc = $null');
  L('for ($i = 1; $i -le 10; $i++) {');
  L('  $svc = Get-Service sshd -ErrorAction SilentlyContinue');
  L('  if ($svc -and $svc.Status -eq "Running") { break }');
  L('  Start-Sleep -Seconds 1');
  L('}');
  L('if (-not $svc) { Fail "the sshd service disappeared right after being started" }');
  L('Say ("sshd service: " + $svc.Status)');
  L('if ($svc.Status -ne "Running") {');
  L('  Fail ("sshd is " + $svc.Status + " instead of Running. Check the config with: " +');
  L('        "& \'" + $sshdExe + "\' -d -f \'" + $cfg + "\'")');
  L('}');
  L('');
  L('$sock = @()');
  L('for ($i = 1; $i -le 10; $i++) {');
  L('  $sock = @(Get-NetTCPConnection -State Listen -LocalPort $SshPort -ErrorAction SilentlyContinue)');
  L('  if ($sock.Count -gt 0) { break }');
  L('  Start-Sleep -Seconds 1');
  L('}');
  L('if ($sock.Count -eq 0) { Fail "sshd is running but nothing is listening on port $SshPort" }');
  L('$onTs = $sock | Where-Object { $_.LocalAddress -eq $tsIp }');
  L('if (-not $onTs) { Fail "sshd is not listening on the Tailscale address ($tsIp)" }');
  L('Say ("listening on " + $tsIp + ":" + $SshPort)');
  L('');
  L('# Firewall rule scoped to the tailnet interface and range ONLY.');
  L('# Never open 22 to the local network.');
  L('$ruleName = "super-subagent-sshd"');
  L('$existingRule = Get-NetFirewallRule -DisplayName $ruleName -ErrorAction SilentlyContinue');
  L('if (-not $existingRule) {');
  L('  Try {');
  L('    New-NetFirewallRule -DisplayName $ruleName -Direction Inbound -Action Allow -Protocol TCP -LocalPort $SshPort -RemoteAddress "100.64.0.0/10" -ErrorAction Stop | Out-Null');
  L('    Say "firewall rule added (tailnet range only)"');
  L('  } Catch { Say ("warning: could not add the firewall rule: " + $_.Exception.Message) }');
  L('} else { Say "firewall rule already present" }');
  L('');

  // --- step 5.5: sshd 自愈 ---
  L('# =====================================================================');
  L('# STEP 5/6 (continued)  Make sshd survive the next reboot');
  L('# =====================================================================');
  L('# WHY: sshd is bound to the Tailscale address on purpose, but at boot it');
  L('# can start before Tailscale has an address, fail to bind, and exit. From');
  L('# then on the machine is unreachable until someone walks over to it --');
  L('# this happened once and had to be fixed with a full reinstall.');
  L('#');
  L('# This registers a task that waits for Tailscale, fixes a stale listen');
  L('# address, and starts sshd if it is not running. It runs as SYSTEM with a');
  L('# 2 minute delay and bounded retries, so it cannot cause a restart storm.');
  L('$healDir = "C:\\ProgramData\\super-subagent"');
  L('if (-not (Test-Path $healDir)) { New-Item -ItemType Directory -Path $healDir -Force | Out-Null }');
  L('$healScript = Join-Path $healDir "sshd-heal.ps1"');
  L('$healBody = ' + "'" + healScriptB64 + "'");
  L('try {');
  L('  [IO.File]::WriteAllBytes($healScript, [Convert]::FromBase64String($healBody))');
  L('  Say "self-healing script written"');
  L('} catch {');
  L('  Say ("warning: could not write the self-healing script: " + $_.Exception.Message)');
  L('}');
  L('');
  L('$regBody = ' + "'" + registerTaskB64 + "'");
  L('$regScript = Join-Path $healDir "register-heal-task.ps1"');
  L('try {');
  L('  [IO.File]::WriteAllBytes($regScript, [Convert]::FromBase64String($regBody))');
  L('  $out = & powershell -NoProfile -NonInteractive -ExecutionPolicy Bypass -File $regScript 2>&1');
  L('  foreach ($line in @($out)) { if ("$line") { Say ("  " + $line) } }');
  L('} catch {');
  L('  Say ("warning: could not register the self-healing task: " + $_.Exception.Message)');
  L('}');
  L('');
  L('# =====================================================================');
  L('# STEP 6/6  Report to the controller');
  L('# =====================================================================');
  L('Say "--- step 6/6: report to the controller ---"');
  L('');
  L('$osName = ""');
  L('try { $osName = (Get-CimInstance Win32_OperatingSystem).Caption } catch { }');
  L('');
  L('$nodeVersion = ""');
  L('try { $nodeVersion = ((& $node.Source --version) 2>&1 | Out-String).Trim() } catch { }');
  L('');
  L('# Report the hostname so the controller can show a human-readable name.');
  L('$report = @{');
  L('  v = 1');
  L('  token = $BeaconToken');
  L('  ts = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()');
  L('  name = $(if ($AgentName) { $AgentName } else { $env:COMPUTERNAME })');
  L('  host = $env:COMPUTERNAME');
  L('  user = $env:USERNAME');
  L('  ips = @($tsIp)');
  L('  os = $osName');
  L('  nodeVersion = $nodeVersion');
  L('  publicKey = ($ControllerPubKey -split " ")[0..1] -join " "');
  L('}');
  L('$body = $report | ConvertTo-Json -Compress');
  L('$url = "http://" + $ControllerIp + ":" + $BeaconPort + "/beacon"');
  L('');
  L('$sent = $false');
  L('for ($i = 1; $i -le 3; $i++) {');
  L('  Try {');
  L('    $r = Invoke-WebRequest -Uri $url -Method POST -Body $body -ContentType "application/json" -TimeoutSec 20 -UseBasicParsing -ErrorAction Stop');
  L('    if ($r.StatusCode -ge 200 -and $r.StatusCode -lt 300) { $sent = $true; break }');
  L('    Say ("attempt " + $i + ": HTTP " + $r.StatusCode + " " + $r.Content)');
  L('  } Catch {');
  L('    $msg = $_.Exception.Message');
  L('    Say ("attempt " + $i + ": " + $msg)');
  L('    # A 4xx means the controller rejected us (bad or expired token).');
  L('    # Retrying cannot help, so stop and say so plainly.');
  L('    if ($msg -match "40[0-9]") { break }');
  L('  }');
  L('  Start-Sleep -Seconds 3');
  L('}');
  L('');
  L('Say ""');
  L('if ($sent) {');
  L('  Say "=== DONE: this machine is now a super-subagent ==="');
  L('  Say ("name:    " + $report.name)');
  L('  Say ("address: " + $tsIp)');
  L('  Say ("ssh:     " + $env:USERNAME + "@" + $tsIp + ":" + $SshPort)');
  L('  Say ""');
  L('  Say "It should now appear in the controller UI as ready."');
  L('} else {');
  L('  Say "=== setup finished, but the controller did not answer ==="');
  L('  Say "The machine is correctly configured and can be added by address."');
  L('  Say ("address: " + $tsIp)');
  L('  Say ""');
  L('  Say "If the controller was off, just start it: it scans the tailnet and"');
  L('  Say "will find this machine by itself."');
  L('}');
  L('Say ("log file: " + $ProgressFile)');

  return lines.join('\r\n') + '\r\n';
}

/**
 * 检查生成的脚本是否是纯 ASCII。
 *
 * 生成端必须自己验证，不能指望调用方。PowerShell 5.1 读无 BOM 文件时按
 * GBK 解码，一个多字节字符就可能让下一行代码静默失效——这种 bug 在
 * 目标机器上表现为"某一步没生效"，极难排查。
 *
 * @returns {{ok:boolean, badIndex?:number, char?:string}}
 */
export function assertAscii(script) {
  for (let i = 0; i < script.length; i++) {
    const c = script.charCodeAt(i);
    if (c > 127) {
      return { ok: false, badIndex: i, char: String.fromCharCode(c) };
    }
  }
  return { ok: true };
}
